class MongoDBService:
    def __init__(self):
        self._client: Optional[MongoClient] = None
        self._db = None
        self._connected = False
        self._last_attempt = 0.0
        self._init_connection()

    def _init_connection(self):
        self._last_attempt = time.time()
        if not settings.is_mongodb_configured:
            logger.info("MongoDB URI not configured. Running in memory mode.")
            return

        try:
            self._client = MongoClient(settings.MONGODB_URI, serverSelectionTimeoutMS=4000)
            # Test actual connection and authentication with ping
            self._client.admin.command('ping')
            self._db = self._client[settings.MONGODB_DB_NAME]
            self._connected = True
            logger.info(f"Connected to MongoDB Atlas database: {settings.MONGODB_DB_NAME}")
            self._ensure_indexes_and_seed()
        except Exception as e:
            logger.warning(f"Could not connect to MongoDB Atlas ({e}). Falling back to local store.")
            self._connected = False
            self._db = None

    @property
    def is_connected(self) -> bool:
        if self._connected and self._db is not None:
            return True
        now = time.time()
        # Cooldown reconnect attempts by at least 30 seconds to prevent blocking requests
        if settings.is_mongodb_configured and not self._connected and (now - self._last_attempt > 30):
            self._init_connection()
        return self._connected

    def _ensure_indexes_and_seed(self):
        if not self._connected or self._db is None:
            return
        try:
            self._db.users.create_index([("email", ASCENDING)], unique=True)
            self._db.otps.create_index([("email", ASCENDING)])
            self._db.notes.create_index([("user_id", ASCENDING), ("created_at", ASCENDING)])
            self._db.flashcards.create_index([("user_id", ASCENDING), ("subject", ASCENDING)])
            self._db.quizzes.create_index([("quiz_id", ASCENDING)], unique=True)
            self._db.attempts.create_index([("user_id", ASCENDING), ("timestamp", ASCENDING)])
            self._db.question_history.create_index([("user_id", ASCENDING), ("topic", ASCENDING), ("created_at", ASCENDING)])
            self._db.question_history.create_index([("user_id", ASCENDING), ("fingerprint", ASCENDING)])

            # Seed sample notes if empty
            if self._db.notes.count_documents({}) == 0:
                self._seed_default_data()
        except Exception as e:
            logger.warning(f"Index creation or seeding warning: {e}")

